//! Writes the TanStack contender's theme (`contenders/tall-table/tanstack/
//! web/src/theme.css`) from gpui-kit's default theme at the pin: the colors
//! the tall table draws with (and the GPUI host's body and status line), as
//! CSS variables, light and dark: the system's by the media query, or the
//! page's where it sets the root's `data-theme`. The DOM side draws the same colors without
//! anyone copying a hex value by hand.
//!
//! `cargo run -p tall-table-gpui --example theme_css` writes it; with
//! `-- --check` it fails if the committed file differs (`just observatory
//! theme-css`).

use gpui_kit::component::{Theme, ThemeColor};
use gpui_kit::{Hsla, Rgba};

const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../tanstack/web/src/theme.css"
);

/// The variables, each with the theme field it's read from. The tall
/// table's (`components/tall-table/src/state.rs`, `tall_table.rs`), the
/// tooltip's (gpui-kit's `Tooltip`: popover colors), and the page's body.
fn colors(theme: &Theme) -> [(&'static str, Hsla); 18] {
    [
        ("background", theme.background),
        ("foreground", theme.foreground),
        ("muted-foreground", theme.muted_foreground),
        ("border", theme.border),
        ("ring", theme.ring),
        ("danger", theme.danger),
        ("table", theme.table),
        ("table-head", theme.table_head),
        ("table-head-foreground", theme.table_head_foreground),
        ("table-even", theme.table_even),
        ("table-active", theme.table_active),
        ("table-row-border", theme.table_row_border),
        ("skeleton", theme.skeleton),
        ("scrollbar", theme.scrollbar),
        ("scrollbar-thumb", theme.scrollbar_thumb),
        ("scrollbar-thumb-hover", theme.scrollbar_thumb_hover),
        ("popover", theme.popover),
        ("popover-foreground", theme.popover_foreground),
    ]
}

/// `#rrggbb`, or `#rrggbbaa` when it isn't opaque.
fn hex(color: Hsla) -> String {
    let Rgba { r, g, b, a } = color.to_rgb();
    let byte = |value: f32| (value.clamp(0.0, 1.0) * 255.0).round() as u8;
    let rgb = format!("#{:02x}{:02x}{:02x}", byte(r), byte(g), byte(b));
    if byte(a) == 255 {
        rgb
    } else {
        format!("{rgb}{:02x}", byte(a))
    }
}

fn block(theme: &Theme, indent: &str) -> String {
    let mut out = String::new();
    for (name, color) in colors(theme) {
        out.push_str(&format!("{indent}--{name}: {};\n", hex(color)));
    }
    out.push_str(&format!(
        "{indent}--radius: {}px;\n",
        f32::from(theme.radius)
    ));
    out
}

fn css() -> String {
    let light = Theme::from(&*ThemeColor::light());
    let dark = Theme::from(&*ThemeColor::dark());
    // The system's theme by the media query, unless the page set one on the
    // root (`?theme=`, `data-theme`; `contenders/contract.ts`).
    format!(
        "/* Generated by `just observatory theme-css` from gpui-kit {}'s default theme\n   \
         (contenders/tall-table/gpui/crate/examples/theme_css.rs). Don't edit. */\n\
         :root {{\n  color-scheme: light dark;\n{}}}\n\
         @media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{}  }}\n}}\n\
         :root[data-theme=\"light\"] {{\n  color-scheme: light;\n}}\n\
         :root[data-theme=\"dark\"] {{\n  color-scheme: dark;\n{}}}\n",
        gpui_kit_version(),
        block(&light, "  "),
        block(&dark, "    "),
        block(&dark, "  "),
    )
}

/// The pinned version, from the workspace's lockfile.
fn gpui_kit_version() -> String {
    let lock = std::fs::read_to_string(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../../../../../Cargo.lock"
    ))
    .expect("reading Cargo.lock");
    let mut lines = lock.lines();
    while let Some(line) = lines.next() {
        if line == "name = \"gpui-kit\""
            && let Some(version) = lines
                .next()
                .and_then(|line| line.strip_prefix("version = \""))
        {
            return version.trim_end_matches('"').to_string();
        }
    }
    panic!("no gpui-kit in Cargo.lock");
}

fn main() {
    let css = css();
    if std::env::args().any(|arg| arg == "--check") {
        let committed = std::fs::read_to_string(OUT).unwrap_or_default();
        if committed != css {
            eprintln!("{OUT} is stale: run `just observatory theme-css`");
            std::process::exit(1);
        }
        println!("theme.css matches gpui-kit's default theme");
    } else {
        std::fs::write(OUT, css).expect("writing theme.css");
        println!("wrote {OUT}");
    }
}
