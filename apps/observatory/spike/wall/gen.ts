// The monitoring wall's instruments, generated once (throwaway; the
// monitoring wall's spike): 8 desks × 50 fictional instruments, a symbol and
// a reference price each, written as literal text to `contenders/wall/instruments.ts` (and the
// desks' names to `names.ts`), which pin them: that file is the record, not this script. A symbol is a seeded
// pronounceable word cut to its first letter and next three consonants (as
// market watch's read as their names' letters), never listed on a US
// exchange (NASDAQ Trader's directories, fetched now, as prep's check is),
// never one of market watch's 50, never repeated. A price is log-uniform in
// its desk's range, to the cent. Not reproducible from the seed alone: a
// rejected symbol uses up draws, so a rerun against another day's listing
// gives other instruments. It refuses to overwrite the pinned file without
// --write.
//
// Usage: node apps/observatory/spike/wall/gen.ts [--write]

import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { INSTRUMENTS } from '../../contenders/market/feed.ts';

const DESKS: [name: string, lo: number, hi: number][] = [
  ['Energy', 18, 160], ['Rail and freight', 14, 130], ['Banks', 12, 95], ['Chips', 25, 480],
  ['Health', 8, 320], ['Retail', 6, 150], ['Materials', 4, 85], ['Utilities', 22, 115],
];
const PER_DESK = 50;

function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const next = rng(0x3a11);
const pick = <T>(xs: readonly T[]): T => xs[Math.floor(next() * xs.length)]!;

const ONSET = ['B', 'BR', 'C', 'CR', 'D', 'DR', 'F', 'G', 'GR', 'H', 'K', 'L', 'M', 'N', 'P', 'PR', 'R', 'S', 'ST', 'T', 'TR', 'V', 'W'];
const VOWEL = ['A', 'E', 'I', 'O', 'U', 'A', 'E', 'O'];
const CODA = ['L', 'N', 'R', 'S', 'T', 'M', 'D', 'K', 'V', 'W', 'X', 'TH', 'ND', 'RN', 'LD', 'NT', 'RK'];
function symbol(): string {
  const word = pick(ONSET) + pick(VOWEL) + pick(CODA) + pick(VOWEL) + pick(CODA);
  const consonants = word.slice(1).replace(/[AEIOU]/g, '');
  return (word[0]! + consonants).slice(0, 4);
}

const listed = new Set<string>();
for (const { url, columns } of [
  { url: 'https://www.nasdaqtrader.com/dynamic/SymDir/nasdaqlisted.txt', columns: ['Symbol'] },
  { url: 'https://www.nasdaqtrader.com/dynamic/SymDir/otherlisted.txt', columns: ['ACT Symbol', 'CQS Symbol', 'NASDAQ Symbol'] },
]) {
  const [header, ...lines] = (await (await fetch(url)).text()).trim().split(/\r?\n/);
  const at = columns.map((c) => header!.split('|').indexOf(c));
  for (const line of lines) for (const c of at) listed.add(line.split('|')[c]!);
}
for (const control of ['AAPL', 'IBM']) if (!listed.has(control)) throw new Error(`control ${control} not listed: directories misread`);

const taken = new Set(INSTRUMENTS.map((i) => i.symbol));
let rejectedListed = 0;
const rows: [number, string, number][] = [];
DESKS.forEach(([, lo, hi], desk) => {
  for (let k = 0; k < PER_DESK; k++) {
    let s = symbol();
    while (s.length < 4 || taken.has(s) || listed.has(s)) {
      if (listed.has(s)) rejectedListed++;
      s = symbol();
    }
    taken.add(s);
    const price = Math.round(Math.exp(Math.log(lo) + next() * (Math.log(hi) - Math.log(lo))) * 100) / 100;
    rows.push([desk, s, price]);
  }
});

const target = join(import.meta.dirname, '../../contenders/wall/instruments.ts');
const namesTarget = join(import.meta.dirname, '../../contenders/wall/names.ts');
if (existsSync(target) && !process.argv.includes('--write')) {
  throw new Error(`${target} is pinned: pass --write to replace it (a rerun against today's listing gives other instruments)`);
}
const lines = rows.map(([d, s, p]) => `  [${d}, '${s}', ${p}],`);
// The headers as the pinned files carry them: a rerun keeps them.
writeFileSync(
  namesTarget,
  `// The monitoring wall's desks, in the order a stop takes them (its first N),\n// each a table's title: a file of its own, so what reads only the names (the\n// scenarios, in every contender's first-paint JS) never imports the 400 rows.\n// Generated by spike/wall/gen.ts with instruments.ts; pinned here as text.\n` +
    `export const DESKS = ${JSON.stringify(DESKS.map(([n]) => n))} as const;\n`,
);
writeFileSync(
  target,
  `// The monitoring wall's 400 fictional instruments, their one home: 8 desks of 50\n// (names.ts), in the feed's order (a tick's instrument is its index here).\n// Generated by spike/wall/gen.ts (seed 0x3a11) against NASDAQ Trader's listing of ${new Date().toISOString().slice(0, 10)};\n// pinned here as text: this file is the record. data/prep.ts writes the wall's\n// file from it, checking again that no symbol is listed on a US exchange.\n` +
    `/** [desk, symbol, reference price]: 50 a desk, in desk order. */\n` +
    `export const WALL_INSTRUMENTS: readonly (readonly [number, string, number])[] = [\n${lines.join('\n')}\n];\n`,
);
console.log(`${rows.length} instruments; ${rejectedListed} listed symbols rejected; ${listed.size} listed symbols read`);
console.log(DESKS.map(([n], d) => `${n}: ${rows.filter((r) => r[0] === d).slice(0, 6).map((r) => `${r[1]} ${r[2]}`).join(', ')}`).join('\n'));
