// Kirkwood's host. GPUI paints first (the title, the time control, the
// table's handle). After its first frame: the scene's module (Three.js),
// on a canvas of its own under GPUI's, and the two files, the elements
// first, each written into the crate's memory as it arrives: held once,
// with no copy on this side. The scene draws the belt from the elements
// where they lie, as soon as both are in; the table opens when the rows
// file is. Last, and never waited on, the sky's stars: the scene's own.
import { boot } from '@seiza/web/bootstrap';
import fontUrl from '@seiza/web/fonts/IBMPlexSans-Regular.ttf?url';
// Generated by wasm-bindgen into web/pkg/ (gitignored); `just kirkwood build` builds it.
import init, {
  belt_counts,
  belt_drawn,
  clock_date,
  clock_state,
  elements_columns,
  elements_ptr,
  elements_rows,
  file_begin,
  file_end,
  file_failed,
  file_progress,
  jupiter_orbit,
  jupiter_place,
  orbit_ramp,
  place_of,
  scene_failed,
  scene_inset,
  scene_scrim,
  scene_scrim_changes,
  scene_years,
  sky_drawn,
  start,
} from '../pkg/kirkwood.js';
// The same asset wasm-bindgen would resolve; named here so the HTML preload and
// `init` fetch one URL (instantiateStreaming needs `application/wasm`).
import wasmUrl from '../pkg/kirkwood_bg.wasm?url';
// What the two files are: each one's length, which a response must have
// (data/MANIFEST.json). The crate then checks each file's header and the
// tables its reads lean on; neither is a check of the file's hash.
import manifest from '../../data/MANIFEST.json';
import { compositeByAlpha } from './alpha.ts';
import type { BeltScene } from './scene.ts';

/** The files in the order they're asked for, with the crate's ids for them
 *  (`web.rs`): the table's a, e, i, and H are the elements'. */
const FILES = [
  { id: 0, name: 'elements.bin' },
  { id: 1, name: 'rows.bin' },
] as const;
/** The columns the scene draws from, all of the elements file's: a, e, i,
 *  the node, the argument of perihelion, the mean anomaly, and H. */
const SCENE_COLUMNS = 7;
/** The sky's file, and the mark set once its stars are the scene's. */
const SKY = 'stars.bin';
const SKY_MARK = 'kirkwood:sky';

type Kirkwood = {
  /** Called by the crate once GPUI's first frame is on screen. */
  firstFrame(): void;
  /** Called by the crate: a wheel over the scene. */
  wheel(x: number, y: number, delta: number): void;
  /** For the checks: the wasm's linear memory in bytes, now and as it was
   *  when the first frame was on screen (before either file). */
  wasmBytes(): number;
  wasmBytesAtFirstFrame: number;
  /** For the checks: the scene, once it's started; whether the views it
   *  was given were over the wasm's own memory; the crate's 64-bit place
   *  for a row and for Jupiter (ecliptic x, y, z in au); the clock; and
   *  the rows the belt draws and doesn't. */
  scene?: BeltScene;
  viewsShareMemory?: boolean;
  placeOf(row: number, years: number): number[];
  jupiter(years: number): number[];
  clock(): { years: number; running: boolean; held: boolean; ended: boolean; first: number; last: number; date: string };
  belt(): { drawn: number; unbound: number };
  /** For the checks: the ramp the scene tints by (each stop's a, then its
   *  red, green, and blue in linear light), and where the page's text lies
   *  over the scene (left, top, width, height, CSS px). */
  ramp(): number[];
  scrim(): number[];
};

let memory: WebAssembly.Memory | undefined;
let scene: BeltScene | undefined;

/** One file into the crate's memory, a piece at a time as it arrives. */
async function hold(file: (typeof FILES)[number], progress: (bytes: number) => void): Promise<void> {
  const { bytes } = manifest[file.name];
  const response = await fetch(`${import.meta.env.BASE_URL}data/${file.name}`);
  if (!response.ok || !response.body) throw new Error(`${file.name}: ${response.status} ${response.statusText}`);
  const at = file_begin(bytes);
  const reader = response.body.getReader();
  let held = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (held + value.length > bytes) throw new Error(`${file.name} is longer than the manifest's ${bytes} bytes`);
      // A view made for this piece alone: the memory growing detaches one.
      new Uint8Array(memory!.buffer, at + held, value.length).set(value);
      held += value.length;
      progress(value.length);
    }
  } catch (error) {
    // The rest of a response that's turned down isn't downloaded.
    void reader.cancel().catch(() => {});
    throw error;
  }
  if (held !== bytes) throw new Error(`${file.name} is ${held} bytes, and the manifest's is ${bytes}`);
  const problem = file_end(file.id);
  if (problem) throw new Error(problem);
}

/** The scene's module, then the scene: the Sun and Jupiter are up before
 *  the asteroids are. */
async function startScene(): Promise<BeltScene> {
  const { startScene } = await import('./scene.ts');
  // The names beside the Sun and Jupiter are the page's text, in the
  // interface's face: the font GPUI was handed, from the cache.
  const face = new FontFace('IBM Plex Sans', `url(${fontUrl})`);
  document.fonts.add(face);
  void face.load().catch(() => {});
  scene = startScene(document.querySelector<HTMLCanvasElement>('#scene')!, document.querySelector<HTMLElement>('#names')!, {
    years: scene_years,
    inset: scene_inset,
    jupiter: jupiter_place,
    jupiterOrbit: jupiter_orbit,
    ramp: orbit_ramp,
    scrim: scene_scrim,
    scrimChanges: scene_scrim_changes,
  });
  kirkwood.scene = scene;
  performance.mark('kirkwood:scene');
  return scene;
}

/** The belt, from the elements where the crate holds them. */
function drawBelt(scene: BeltScene): void {
  const rows = elements_rows();
  if (elements_columns() !== SCENE_COLUMNS) throw new Error("the elements' columns aren't the scene's seven");
  scene.setElements(() => {
    // Views over the crate's own columns: no copy on this side. Made here,
    // inside the call that uploads them.
    const at = elements_ptr();
    const views = Array.from({ length: SCENE_COLUMNS }, (_, column) => new Float32Array(memory!.buffer, at + column * rows * 4, rows));
    kirkwood.viewsShareMemory = views.every((view) => view.buffer === memory!.buffer);
    return views;
  }, rows);
  performance.mark('kirkwood:belt');
  // The page's counts are counted now, and time starts to move.
  belt_drawn();
}

async function afterFirstFrame(): Promise<void> {
  const total = FILES.reduce((sum, file) => sum + manifest[file.name].bytes, 0);
  let received = 0;
  // The scene's module loads beside the elements; neither waits on the other.
  const started = startScene();
  // A scene that doesn't start, or can't draw the belt, says so once, on
  // the page; the files go on arriving, and the table doesn't need it.
  const sceneFailed = (error: unknown) => {
    console.error(error);
    scene_failed(error instanceof Error ? error.message : String(error));
  };
  started.catch(sceneFailed);
  let belt: Promise<void> | undefined;
  let failed: unknown;
  try {
    for (const file of FILES) {
      await hold(file, (bytes) => {
        received += bytes;
        file_progress(received, total);
      });
      // The belt is drawn once the elements are held and the scene is up;
      // the rows file is asked for meanwhile.
      if (file.name === 'elements.bin') {
        // A scene that never started has said so already.
        belt = started.then(
          (scene) => {
            try {
              drawBelt(scene);
            } catch (error) {
              sceneFailed(error);
            }
          },
          () => {},
        );
      }
    }
  } catch (error) {
    file_failed(error instanceof Error ? error.message : String(error));
    failed = error;
  }
  await belt;
  // The sky comes last, behind everything a row waits on, and nothing
  // waits on it: a scene that started gets its stars whatever became of
  // the files.
  await started.then(holdSky, () => {});
  if (failed) throw failed;
}

/** The sky's stars, the scene's own: they aren't rows, so they aren't the
 *  crate's. Without them the page is whole: a failure is the console's. */
async function holdSky(scene: BeltScene): Promise<void> {
  // Not asked for where it wouldn't be drawn.
  if (!scene.wantsSky) return;
  try {
    const response = await fetch(`${import.meta.env.BASE_URL}data/${SKY}`);
    if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
    const file = await response.arrayBuffer();
    if (file.byteLength !== manifest[SKY].bytes) throw new Error(`${file.byteLength} bytes, and the manifest's is ${manifest[SKY].bytes}`);
    scene.setSky(file);
    performance.mark(SKY_MARK);
    // The page says whose stars they are, and that they aren't rows.
    sky_drawn();
  } catch (error) {
    console.warn(`no sky (${SKY}):`, error);
  }
}

const kirkwood: Kirkwood = {
  firstFrame: () => {
    kirkwood.wasmBytesAtFirstFrame = kirkwood.wasmBytes();
    void afterFirstFrame();
  },
  wheel: (x, y, delta) => scene?.wheel(x, y, delta),
  wasmBytes: () => memory?.buffer.byteLength ?? 0,
  wasmBytesAtFirstFrame: 0,
  placeOf: (row, years) => Array.from(place_of(row, years)),
  jupiter: (years) => Array.from(jupiter_place(years)),
  clock: () => {
    const [years, running, held, ended, first, last] = Array.from(clock_state());
    return { years: years!, running: !!running, held: !!held, ended: !!ended, first: first!, last: last!, date: clock_date() };
  },
  belt: () => {
    const [drawn, unbound] = Array.from(belt_counts());
    return { drawn: drawn!, unbound: unbound! };
  },
  ramp: () => Array.from(orbit_ramp()),
  scrim: () => Array.from(scene_scrim()),
};
(globalThis as unknown as { __kirkwood: Kirkwood }).__kirkwood = kirkwood;

// GPUI's canvas composites by its alpha, so the scene's shows wherever GPUI
// drew nothing: set up before the wasm configures its canvas.
compositeByAlpha();

void boot({
  init: async () => {
    memory = (await init({ module_or_path: wasmUrl })).memory;
  },
  start,
  fontUrl,
  wasmUrl,
});
