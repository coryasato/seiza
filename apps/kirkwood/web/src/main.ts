/** One file into the crate's memory, a piece at a time as it arrives.
 *  `progress` hears each piece's bytes, then the file's bytes held so far. */
async function hold(file: (typeof FILES)[number], progress: (bytes: number, held: number) => void): Promise<void> {
  const { bytes } = manifest[file.name];
  const response = await fetch(`${import.meta.env.BASE_URL}data/${file.name}`);
  if (!response.ok || !response.body) throw new Error(`${file.name}: ${response.status} ${response.statusText}`);
  const at = file_begin(file.id, bytes);
  const reader = response.body.getReader();
  let held = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (held + value.length > bytes) throw new Error(`${file.name} is longer than the manifest's ${bytes} bytes`);
      // A view made for this piece alone: the memory growing detaches one.
      new Uint8Array(memory!.buffer, at + held, value.length).set(value);
      held += value.length;
      progress(value.length, held);
    }
  } catch (error) {
    // The rest of a response that's turned down isn't downloaded.
    void reader.cancel().catch(() => {});
    throw error;
  }
  if (held !== bytes) throw new Error(`${file.name} is ${held} bytes, and the manifest's is ${bytes}`);
  const problem = file_end(file.id);
  if (problem) throw new Error(problem);
}

