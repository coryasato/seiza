// Kirkwood's host. GPUI paints first (the title, the time control, the
// table's handle). After its first frame: the scene's module (Three.js),
// on a canvas of its own under GPUI's, and the two files, the elements
// first, each written into the crate's memory as it arrives: held once,
// with no copy on this side. The elements are in blocks of rows, and the
// scene draws each block from where it lies as soon as it's whole, so the
// belt fills in as it arrives; the table opens when the rows file is in.
// Last, and never waited on, the sky's stars: the scene's own.
import { boot } from '@seiza/web/bootstrap';
import fontUrl from '@seiza/web/fonts/IBMPlexSans-Regular.ttf?url';
// Generated by wasm-bindgen into web/pkg/ (gitignored); `just kirkwood build` builds it.
